                <section id="verifikasi-akun" class="scroll-mt-24 space-y-3 border-t border-slate-200 pt-8">
                    <h2 class="text-lg sm:text-xl font-black text-slate-900">
                        1. Pendaftaran dan Verifikasi Identitas Mahasiswa
                    </h2>
                    <p class="text-sm text-slate-700 leading-relaxed">
                        Untuk menjaga keamanan komunitas kos di Kota Malang, setiap pengguna yang mendaftar wajib melewati salah satu dari dua jalur validasi identitas berikut:
                    </p>
                    <ol class="list-decimal list-inside space-y-2.5 text-sm text-slate-700 leading-relaxed pl-1">
                        <li>
                            <strong class="text-slate-900">Jalur Email Kampus (Aktivasi Instan):</strong> Pendaftar yang menggunakan domain email resmi perguruan tinggi di Malang yang terdaftar pada sistem (seperti <code class="px-1.5 py-0.5 rounded bg-slate-100 text-slate-900 text-xs font-mono">@student.polinema.ac.id</code>, <code class="px-1.5 py-0.5 rounded bg-slate-100 text-slate-900 text-xs font-mono">@student.ub.ac.id</code>, <code class="px-1.5 py-0.5 rounded bg-slate-100 text-slate-900 text-xs font-mono">@umm.ac.id</code>) akan menerima kode OTP 6 digit. Data pendaftaran disimpan sementara pada cache selama 10 menit dan akun langsung aktif setelah kode OTP diverifikasi.
                        </li>
                        <li>
                            <strong class="text-slate-900">Jalur Email Umum (Verifikasi Berkas KTM):</strong> Pendaftar yang menggunakan email publik (seperti Gmail atau Yahoo), termasuk melalui login Google OAuth non-kampus, wajib melampirkan foto Kartu Tanda Mahasiswa (KTM) aktif berformat JPG atau PNG dengan ukuran maksimal 2 MB. Akun akan berstatus <em>pending</em> hingga administrator menyetujui keabsahan berkas KTM tersebut.
                        </li>
                        <li>
                            <strong class="text-slate-900">Kebenaran Data:</strong> Pengguna bertanggung jawab penuh atas keaslian nama lengkap, Nomor Induk Mahasiswa (NIM), asal kampus, dan berkas KTM yang diunggah. Pemalsuan identitas akan berakibat pada penolakan pendaftaran atau penonaktifan akun secara permanen.
                        </li>
                    </ol>
                </section>

                <section id="aturan-katalog" class="scroll-mt-24 space-y-3 border-t border-slate-200 pt-8">
                    <h2 class="text-lg sm:text-xl font-black text-slate-900">
                        2. Ketentuan Katalog, Integritas Harga, dan Mode Peran
                    </h2>
                    <p class="text-sm text-slate-700 leading-relaxed">
                        Pengguna yang telah terverifikasi dapat mengakses fitur katalog, memasang iklan barang, dan mempublikasikan permintaan barang (Wanted Ads) dengan ketentuan:
                    </p>
                    <ul class="list-disc list-inside space-y-2.5 text-sm text-slate-700 leading-relaxed pl-1">
                        <li>
                            <strong class="text-slate-900"> Pembatasan Akses Pengunjung (Guest):</strong> Pengunjung yang belum masuk ke akun hanya dapat melihat maksimal 10 iklan di beranda dan tidak dapat melihat detail lengkap maupun menghubungi penjual.
                        </li>
                        <li>
                            <strong class="text-slate-900">Mode Penjual dan Mode Pembeli:</strong> Pemasangan iklan katalog, pembukaan lelang, pengajuan boost, serta penawaran barang ke papan Wanted Ads hanya dapat dilakukan saat akun berada pada <strong>Mode Penjual</strong>. Sebaliknya, pembuatan pengumuman Wanted Ads dan pengajuan tawaran lelang (bidding) hanya dapat dilakukan pada <strong>Mode Pembeli</strong>.
                        </li>
                        <li>
                            <strong class="text-slate-900">Aturan Harga dan Foto:</strong> Harga jual barang wajib bernilai minimal Rp1.000 dan merupakan kelipatan genap Rp1.000 (tidak menggunakan angka satuan atau ratusan rupiah). Setiap iklan wajib menyertakan minimal 1 foto dan maksimal 5 foto asli kondisi barang dengan ukuran masing-masing berkas maksimal 5 MB.
                        </li>
                        <li>
                            <strong class="text-slate-900">Pembaruan Status Barang:</strong> Penjual wajib segera mengubah status iklan menjadi <em>Terjual</em> melalui dasbor apabila barang telah berpindah tangan agar tidak menimbulkan penawaran ganda dari mahasiswa lain.
                        </li>
                    </ul>
                </section>

                <section id="aturan-lelang" class="scroll-mt-24 space-y-3 border-t border-slate-200 pt-8">
                    <h2 class="text-lg sm:text-xl font-black text-slate-900">
                        3. Mekanisme Lelang Terbuka
                    </h2>
                    <p class="text-sm text-slate-700 leading-relaxed">
                        Fitur lelang terbuka dirancang agar perlengkapan kos dapat ditawar secara transparan mengikuti waktu server Lungsur.in:
                    </p>
                    <ol class="list-decimal list-inside space-y-2.5 text-sm text-slate-700 leading-relaxed pl-1">
                        <li>
                            <strong class="text-slate-900">Persetujuan Pra-Tayang:</strong> Sesi lelang yang diajukan penjual baru akan tayang dan memulai hitung mundur setelah bukti pembayaran biaya pembukaan lelang diverifikasi oleh administrator.
                        </li>
                        <li>
                            <strong class="text-slate-900">Larangan Menawar Barang Sendiri (Anti Self-Bidding):</strong> Penjual dilarang mengajukan tawaran pada sesi lelang miliknya sendiri. Peserta yang sedang memegang posisi penawar tertinggi saat ini juga tidak dapat mengajukan tawaran baru sebelum posisinya dilampaui peserta lain.
                        </li>
                        <li>
                            <strong class="text-slate-900">Perpanjangan Waktu Otomatis (Anti-Sniping):</strong> Apabila terdapat tawaran sah yang masuk ketika sisa waktu lelang kurang dari atau sama dengan 5 menit, sistem secara otomatis menambahkan waktu 5 menit pada timer lelang untuk memberikan kesempatan yang adil bagi penawar lain.
                        </li>
                        <li>
                            <strong class="text-slate-900">Kemenangan Instan (Bid Cap / Auto-Win):</strong> Apabila penjual menetapkan batas harga tertinggi (Bid Cap) dan seorang peserta memasukkan nominal tawaran yang menyentuh angka tersebut, sesi lelang langsung ditutup saat itu juga dan peserta tersebut ditetapkan sebagai pemenang lelang.
                        </li>
                    </ol>
                </section>

                <section id="biaya-layanan" class="scroll-mt-24 space-y-3 border-t border-slate-200 pt-8">
                    <h2 class="text-lg sm:text-xl font-black text-slate-900">
                        4. Biaya Pembukaan Lelang dan Promosi (Boost Iklan)
                    </h2>
                    <p class="text-sm text-slate-700 leading-relaxed">
                        Lungsur.in menerapkan biaya administrasi mikro sebesar <strong>Rp5.000</strong> untuk dua layanan opsional bagi penjual:
                    </p>
                    <ul class="list-disc list-inside space-y-2.5 text-sm text-slate-700 leading-relaxed pl-1">
                        <li>
                            <strong class="text-slate-900">Pembukaan Sesi Lelang Terbuka (Rp5.000 per sesi):</strong> Dibayarkan melalui pemindaian kode QRIS statis pengelola saat mengajukan pembukaan lelang.
                        </li>
                        <li>
                            <strong class="text-slate-900">Promosi Sundul Iklan / Boost (Rp5.000 per pengajuan):</strong> Menempatkan iklan pada urutan prioritas di bagian atas katalog setelah bukti pembayaran QRIS statis disetujui oleh administrator.
                        </li>
                        <li>
                            <strong class="text-slate-900">Ketentuan Bukti Pembayaran:</strong> Penjual wajib mengunggah tangkapan layar atau foto bukti transfer QRIS yang sah (format JPG/PNG, maksimal 2 MB). Biaya layanan yang telah diverifikasi dan diaktifkan oleh administrator tidak dapat ditarik kembali (non-refundable). Apabila pengajuan ditolak karena bukti pembayaran tidak valid, administrator akan mencantumkan alasan penolakan pada dasbor penjual.
                        </li>
                    </ul>
                </section>

                <section id="transaksi-cod" class="scroll-mt-24 space-y-3 border-t border-slate-200 pt-8">
                    <h2 class="text-lg sm:text-xl font-black text-slate-900">
                        5. Kesepakatan Transaksi, Ruang Obrolan, dan COD
                    </h2>
                    <p class="text-sm text-slate-700 leading-relaxed">
                        Seluruh komunikasi tawar-menawar dan penentuan jadwal serah terima barang dilakukan melalui fitur ruang obrolan internal (In-App Chat) Lungsur.in:
                    </p>
                    <ul class="list-disc list-inside space-y-2.5 text-sm text-slate-700 leading-relaxed pl-1">
                        <li>
                            <strong class="text-slate-900">Perlindungan Privasi Kontak:</strong> Pengguna disarankan bernegosiasi di dalam ruang obrolan aplikasi tanpa membagikan nomor telepon pribadi secara terbuka di deskripsi iklan publik.
                        </li>
                        <li>
                            <strong class="text-slate-900">Prosedur Cash on Delivery (COD):</strong> Pembeli dan penjual wajib memeriksa kondisi fisik barang secara langsung saat bertemu sebelum menyerahkan pembayaran. Disarankan memilih lokasi pertemuan yang aman dan ramai di lingkungan kampus atau area publik Kota Malang pada jam wajar.
                        </li>
                        <li>
                            <strong class="text-slate-900">Penyelesaian Sengketa Fisik:</strong> Karena pembayaran harga barang dilakukan di luar sistem, Lungsur.in tidak menanggung ganti rugi finansial atas kerusakan barang pasca-COD, namun akan menindak tegas akun yang terbukti melakukan penipuan berdasarkan laporan pengguna.
                        </li>
                    </ul>
                </section>

